//Operadores de atribuição em Javascript

//Atribuição básica (=)
let a= 33;
console.log(`Valor de inicial de a: ${a}`);

//atribuição de adição
a += 5
console.log(`Após a += 5, valor de a: ${a}`);

//atribuição de subtração
a -= 3
console.log(`Após a -= 3, valor de a: ${a}`);

// Operador de Atribuição de Multiplicação (*=)
a *= 5
console.log(`Após a *= 5, valor de a: ${a}`);

//operador de divisão
a /= 2
console.log(`Após a  /= 2, valor de a: ${a}`);

//operador de Porcentagem ou Resto (%=)
a %= 5
console.log(`Após a %= 5, valor de a: ${a}`);

//operador de Exponenciação (**=)
a **= 7;
console.log(`Após a **= 7, valor de a: ${a}`);